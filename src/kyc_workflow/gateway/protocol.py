"""Shapes and contracts for model access.

Every model call in the workflow goes through a `ModelGateway`. The only
implementation that reaches a model is `HeliosGateway`, which delegates to a
`ModelBackend`. The workflow never sees a provider SDK.

Design rules that these shapes enforce:

- A request always carries `case_id` and `analyst_id`. They travel with the
  call as metadata so the bank can trace who asked for what. They are not a
  permission boundary: the gateway runs as one service identity.
- Tools are allowed. Helios today serves only the Gemini path's older tool
  schema; the working assumption is that approving Claude behind Helios
  brings Claude's tool use with it, so the gateway passes tools through
  unchanged. The workflow itself needs no tools because the code decides the
  path and the model only reads and compares; structured output replaces
  tool use there. The chat interface uses tools.
- `system` is the stable part (instructions and policy text) and is cached;
  `user` (one message) or `messages` (a conversation) is the changing part.
"""

from __future__ import annotations

from typing import Any, Literal, Protocol

from pydantic import BaseModel, ConfigDict, Field, model_validator


class ToolDef(BaseModel):
    """A tool the model may call, in Messages API shape."""

    name: str
    description: str = ""
    input_schema: dict[str, Any] = Field(default_factory=lambda: {"type": "object", "properties": {}})


class ToolCall(BaseModel):
    """A tool call the model made."""

    id: str
    name: str
    input: dict[str, Any] = Field(default_factory=dict)


class ModelRequest(BaseModel):
    """One call to the model, as the workflow sees it."""

    model_config = ConfigDict(arbitrary_types_allowed=True, frozen=True)

    case_id: str
    analyst_id: str
    system: str = Field(description="Stable instructions and policy text. Cached.")
    user: str | None = Field(default=None, description="Case material for a single-turn call.")
    messages: list[dict[str, Any]] | None = Field(
        default=None,
        description="A conversation in Messages API shape (alternative to `user`).",
    )
    tools: list[ToolDef] | None = Field(default=None, description="Tools the model may call.")
    output_schema: type[BaseModel] | None = Field(
        default=None,
        description="Pydantic model the response must conform to (structured output).",
    )
    max_tokens: int = 4096
    request_id: str | None = Field(
        default=None, description="Trace id; generated by the gateway if absent."
    )
    model: str | None = Field(
        default=None, description="Override the configured model. Must be on the allowlist."
    )
    effort: Literal["low", "medium", "high", "max"] | None = Field(
        default=None, description="How much the model should think (output_config.effort). None leaves the model's default."
    )

    @model_validator(mode="after")
    def _one_of_user_or_messages(self):
        if (self.user is None) == (self.messages is None):
            raise ValueError("give exactly one of `user` or `messages`")
        if self.tools and self.output_schema:
            raise ValueError("tools and output_schema cannot be combined")
        return self

    def conversation(self) -> list[dict[str, Any]]:
        return self.messages if self.messages is not None else [{"role": "user", "content": self.user}]


class TokenUsage(BaseModel):
    input_tokens: int = 0
    output_tokens: int = 0
    cache_read_input_tokens: int = 0
    cache_creation_input_tokens: int = 0


class BackendResult(BaseModel):
    """What a backend returns to the gateway."""

    model_config = ConfigDict(arbitrary_types_allowed=True)

    model: str
    text: str
    parsed: BaseModel | None = None
    stop_reason: str | None = None
    usage: TokenUsage = Field(default_factory=TokenUsage)
    provider_request_id: str | None = None
    tool_calls: list[ToolCall] = Field(default_factory=list)
    content_blocks: list[dict[str, Any]] = Field(
        default_factory=list,
        description="The assistant turn verbatim, to append to a conversation.",
    )


class ModelResponse(BaseModel):
    """What the workflow gets back."""

    model_config = ConfigDict(arbitrary_types_allowed=True)

    request_id: str
    model: str
    text: str
    parsed: BaseModel | None = None
    stop_reason: str | None = None
    usage: TokenUsage = Field(default_factory=TokenUsage)
    latency_ms: float = 0.0
    attempts: int = 1
    tool_calls: list[ToolCall] = Field(default_factory=list)
    content_blocks: list[dict[str, Any]] = Field(default_factory=list)


class GatewayError(Exception):
    """Base for everything the gateway raises. Messages never contain content."""


class HeliosRejected(GatewayError):
    """Helios refused the request before it reached a model (policy, allowlist, metadata)."""


class HeliosUnsupported(GatewayError):
    """The feature is not on Helios's list (embeddings, batch)."""


class HeliosUnavailable(GatewayError):
    """The pinned region failed and retries are exhausted. There is no failover."""


class BackendError(Exception):
    """A backend failure. `transient` tells the gateway whether a retry makes sense."""

    def __init__(self, message: str, *, transient: bool, cause: Exception | None = None):
        super().__init__(message)
        self.transient = transient
        self.cause = cause


class ModelBackend(Protocol):
    """Whatever actually talks to a model. The gateway is the only caller."""

    def complete(
        self,
        *,
        model: str,
        system: str,
        messages: list[dict[str, Any]],
        tools: list[ToolDef] | None,
        output_schema: type[BaseModel] | None,
        max_tokens: int,
        metadata_user_id: str,
        effort: str | None = None,
    ) -> BackendResult: ...


class ModelGateway(Protocol):
    """What the workflow depends on."""

    def complete(self, request: ModelRequest) -> ModelResponse: ...
